insert into customers (name, email, city, created_at)
select first || ' ' || last,
       'user' || g || '@example.com',
       (array['Нови-Сад','Белград','Ниш','Суботица','Крагуевац','Москва','Санкт-Петербург'])[1 + floor(random() * 7)::int],
       now() - (random() * interval '730 days')
from generate_series(1, 500) as g,
     lateral (select (array['Анна','Марко','Елена','Никола','Иван','Мария','Стефан','Ольга','Душан','Милица'])[1 + floor(random() * 10)::int] as first,
                     (array['Петрович','Иванова','Јовић','Смирнов','Николич','Кузнецова','Марковић','Попов'])[1 + floor(random() * 8)::int] as last
              where g > 0) as n;

insert into orders (customer_id, created_at, status)
select 1 + floor(random() * 500)::int,
       now() - (random() * interval '365 days'),
       (array['new','paid','paid','shipped','shipped','shipped','cancelled'])[1 + floor(random() * 7)::int]
from generate_series(1, 5000);

insert into order_items (order_id, book_id, qty, price)
select o.id, b.id, 1 + floor(random() * 3)::int, b.price
from orders o
cross join lateral (
    select id, price from books
    where o.id > 0  -- ссылка на o: подзапрос выполняется для каждой строки заново
    order by random()
    limit 1 + floor(random() * 3)::int
) b;

